
from crewai import Task
from app.agents.risk_agent import risk_agent


risk_task = Task(
    description="""
    Conduct an evidence-based financial risk assessment of {company}.

    INPUT:
    You will receive the sentiment analysis report generated by Agent 4:

    {sentiment_report}

    Your responsibility is to identify, evaluate, prioritize,
    and explain the company's important risks.

    IMPORTANT: The sentiment report is your primary evidence source.
    Do not invent facts or assume risks that are not supported by it.

    1. FINANCIAL RISKS
    Evaluate:
    - Profitability and margin deterioration.
    - Liquidity weaknesses.
    - Debt and leverage concerns.
    - Cash flow sustainability.

    2. BUSINESS AND OPERATIONAL RISKS
    Evaluate business or operational risks only when the
    input report provides supporting evidence.

    3. MARKET AND TECHNICAL RISKS
    Evaluate:
    - Short-term and long-term trend differences.
    - Bearish moving-average alignment.
    - RSI and MACD signals.
    - Volume confirmation.
    - Market uncertainty.

    Do not describe positive short-term momentum as negative.
    Distinguish short-term momentum from the long-term trend.

    4. NEWS AND SENTIMENT RISKS
    Evaluate negative company developments, regulatory concerns,
    and investor sentiment only if explicitly supported by the
    input report.

    5. RISK EVALUATION RULES

    For every identified risk, provide:

    - Risk category.
    - Risk description.
    - Specific evidence from the input.
    - Likelihood: Low, Moderate, or High.
    - Potential impact: Low, Moderate, or High.
    - Severity: Low, Moderate, High, or Critical.
    - Time horizon.
    - Suggested monitoring action.

    Severity must be justified by the available evidence.
    Do not automatically classify a risk as High.

    Distinguish:
    - Confirmed observation.
    - Potential risk.
    - Information gap.

    A financial ratio below 1 is a monitoring consideration,
    not automatic proof of financial distress.

    An increase in absolute debt does not automatically mean
    the debt-to-equity ratio is high.

    A technical indicator is not a guaranteed price prediction.

    6. RISK DEDUPLICATION

    Combine risks that describe the same underlying issue.
    Avoid repeating the same evidence under different categories.
    Prioritize approximately 5-8 meaningful risks when supported.
    Do not invent additional risks to reach a target number.

    7. RISK MITIGATION

    Identify positive factors that are explicitly supported
    by the input report.

    Do not assume that the company has effective risk
    management, strong financial controls, or other strengths
    without evidence.

    8. FINAL REPORT FORMAT

    # Risk Analysis Report

    ## 1. Executive Risk Summary
    Overall risk profile and main observations.

    ## 2. Identified and Prioritized Risks
    Present distinct risks with evidence, likelihood, impact,
    severity, time horizon, and monitoring actions.

    ## 3. Risk Classification Summary
    Summarize Low, Moderate, High, and Critical risks.

    ## 4. Top Three Risk Priorities
    Identify the three most important risks and explain why.

    ## 5. Positive Risk-Mitigating Factors
    Include only evidence-supported positive factors.

    ## 6. Information Gaps
    Explain which risks cannot be reliably assessed.

    ## 7. Overall Risk Conclusion
    Provide a balanced, evidence-based conclusion.

    FINAL RULES:
    - Never fabricate financial figures or company developments.
    - Never claim that Agent 4 reported something it did not.
    - Do not repeat the same risk in multiple sections unnecessarily.
    - Do not provide personalized investment advice.
    - If evidence is insufficient, explicitly say so.
    """,

    expected_output=(
        "A concise, evidence-based financial risk report with "
        "prioritized risks, supporting evidence, likelihood, "
        "impact, severity, time horizon, mitigating factors, "
        "and information gaps."
    ),

    agent=risk_agent
)
